def _expand(spec):
    """Developpe « 01 05 09-12 » en ['01', '05', '09', '10', '11', '12'].

    L'ordre est conserve (frequence decroissante) ; les doublons sont
    ecartes : un enfant cite deux fois garde sa premiere position.
    """
    out, seen = [], set()
    for token in spec.split():
        if "-" in token:
            lo, hi = token.split("-")
            items = [f"{n:02d}" for n in range(int(lo), int(hi) + 1)]
        else:
            items = [token]
        for item in items:
            if item not in seen:
                seen.add(item)
                out.append(item)
    return out


